// ─── 실패까지 남길 반복 수 (RIR) ────────────────────────────────────────────
/**
 * 근비대는 실패에 가까울수록 유리하나, 고중량 컴파운드에서 실패까지 가는 것은
 * 피로 대비 이득이 낮고 부상 위험이 크다. 종목 성격에 따라 범위를 나눈다.
 */
export function rirFor(e: Exercise): { range: string; note: string } {
  if (e.rest >= 120) {
    return {
      range: '1~3 RIR',
      note: '고중량 다관절 종목 — 실패 직전까지 가지 말고 2회 정도 남기세요. 자세가 무너지는 시점이 곧 한계입니다.',
    };
  }
  if (e.ppl === 'core' || e.r.includes('초')) {
    return {
      range: '자세 유지 한계까지',
      note: '시간 기반 종목은 반복 수가 아니라 정렬이 무너지기 직전까지를 한 세트로 봅니다.',
    };
  }
  return {
    range: '0~2 RIR',
    note: '고립 종목은 실패에 가깝게 가도 회복 부담이 적습니다. 마지막 세트는 한계까지 밀어도 좋습니다.',
  };
}

