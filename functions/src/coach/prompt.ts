/** 가변부 — 마지막 user 턴 앞에 붙인다 */
export function buildTurn(o: {
  intent: Intent;
  injury: boolean;
  signals: string;
  data: string;
  question: string;
}): string {
  return [
    `<intent>${o.intent}</intent>`,
    ...(o.injury ? ['<injury>있음</injury>'] : []),
    `<signals>\n${o.signals}\n</signals>`,
    ...(o.data ? [`<data>\n${o.data}\n</data>`] : []),
    '',
    o.question,
  ].join('\n');
}
