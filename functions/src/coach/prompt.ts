/**
 * 공통 — 규칙 + 앱 사용법 · 인사 가이드(짧아서 따로 묶지 않는다).
 * Haiku 4.5 는 4,096토큰이 넘어야 캐시된다 — 공통이 그보다 짧으면 "공통만 캐시에서 읽기" 가 안 된다(지금 약 4,900토큰).
 */
const BASE = [ROLE, INPUTS, HOW, RULES, OUTPUT, NEVER, APP, GENERAL].join('\n\n');

const PACKS: Record<string, string> = { diet: DIET, workout: WORKOUT, progress: PROGRESS, motivation: MOTIVATION };

/**
 * 고정부 — [공통] 또는 [공통, 질문 종류별 묶음]. 덩어리마다 캐시 지점이다:
 * 같은 종류의 질문이 5분 안에 또 오면 전체를, 다른 종류면 공통만 캐시에서 읽는다.
 */
export function systemFor(intent: Intent | string): string[] {
  const pack = PACKS[intent];
  return pack ? [BASE, pack] : [BASE];
}

/** 묶음별 글 — 길이 확인 · 중복 검사용 */
export const SYSTEM_PARTS: Record<string, string> = { base: BASE, ...PACKS };

/** 검증기 허용 숫자에 넣을 고정 자료(식품표) */
export const STATIC_NUMBERS = FOOD_FACTS;

/** 질문 종류별로 앱 데이터(<data>)에서 남길 줄 — 운동 질문에 칼로리 줄을 주면 답이 칼로리로 시작한다 */
const DATA_FOR: Record<string, string[]> = {
  diet: ['사용자', '목표', '환경', '내 변화 프로젝트'],
  progress: ['사용자', '목표', '환경', '내 변화 프로젝트'],
  workout: ['목표', '환경', '현재 플랜', '최근 기록', '이번 주 부위별 세트'],
  motivation: ['목표', '환경', '현재 플랜'],
  general: ['목표', '환경'],
  app: [],
};

export function sliceData(intent: string, data: string): string {
  const keep = DATA_FOR[intent];
  if (!keep || !data) return data;
  const lines = data.split('\n');
  const known = lines.filter((l) => /^(사용자|목표|환경|현재 플랜|최근 기록|이번 주 부위별 세트|내 변화 프로젝트):/.test(l));
  // 옛 앱처럼 줄 머리말이 다르면 거르지 않고 그대로 준다
  if (known.length < 2) return keep.length ? data : '';
  return lines.filter((l) => keep.some((k) => l.startsWith(`${k}:`))).join('\n');
}

/** 가변부 — 마지막 user 턴을 이것으로 바꾼다 */
export function buildTurn(o: {
  intent: Intent;
  injury: boolean;
  status: string[];
  focus: Focus['focus'];
  win: Focus['win'];
  data: string;
  question: string;
  /** 질문에 맞춰 고른 운동 지식(know.knowFor) */
  know?: string[];
  /** 의욕 질문의 작은 행동(know.stepFor) */
  step?: string | null;
  /** 승인 경고 문형 대상(know.warnFor) */
  warn?: string | null;
}): string {
  const data = sliceData(o.intent, o.data);
  return [
    `<intent>${o.intent}</intent>`,
    ...(o.injury ? ['<injury>회원이 아픈 곳을 말함 — 그 부위를 쓰는 종목 제외</injury>'] : []),
    ...(o.status.length ? [`<status>\n${o.status.map((s) => `- ${s}`).join('\n')}\n</status>`] : []),
    ...(o.focus
      ? [o.focus.mode === 'main'
        ? `<focus>\n사실: ${o.focus.text}\n할 일: ${o.focus.action}\n</focus>`
        // 끝 문장은 서버가 붙인다. 식단 · 진행 답은 그 내용과 어긋나면 안 되니 모델에도 보여 주고,
        // 운동 · 의욕 답에는 보여 주지 않는다(보여 주면 묻지 않은 체중 이야기를 제 글에도 쓴다)
        : o.intent === 'diet' || o.intent === 'progress' ? `<aside>${o.focus.say}</aside>` : ''].filter(Boolean)
      : []),
    // 운동 질문의 성과는 서버가 응원 줄로 붙인다(where 'cheer') — 모델에는 주지 않는다
    ...(o.win?.where === 'text' ? [`<win>${o.win.text}</win>`] : []),
    ...(o.know?.length ? [`<know>\n${o.know.map((k) => `- ${k}`).join('\n')}\n</know>`] : []),
    ...(o.step ? [`<step>${o.step}</step>`] : []),
    ...(o.warn ? [`<allow_warning>${o.warn}</allow_warning>`] : []),
    ...(data ? [`<data>\n${data}\n</data>`] : []),
    `<question>${o.question}</question>`,
  ].join('\n');
}
