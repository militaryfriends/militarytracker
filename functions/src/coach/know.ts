const planNames = (data: string) => (data.match(/현재 플랜:\s*([^\n]*)/)?.[1] ?? '');

export function knowFor(intent: Intent | string, question: string, data: string): string[] {
  if (intent !== 'workout' && intent !== 'progress') return [];
  const q = question.replace(/\s+/g, ' ');
  const home = /환경:\s*집/.test(data);
  const out: string[] = [];
  if (intent === 'workout' && ASKS_SWAP.test(q)) {
    // 질문에 종목이 있으면 그 종목, 없으면("사람 많을 때 대체 운동") 회원 플랜의 종목들
    let hits = SWAPS.filter(([re]) => re.test(q));
    if (!hits.length) hits = SWAPS.filter(([re]) => re.test(planNames(data))).slice(0, 3);
    for (const [re, gym, house, note] of hits.slice(0, 3)) {
      const name = (q.match(re) ?? planNames(data).match(re))?.[0] ?? '';
      out.push(`대체 종목 — ${name} 대신: ${home ? house : gym}${note ? ` (${note})` : ''}. 여기 적힌 것에서 고르고, "같은 계열의 움직임" 이라고 설명한다.`);
    }
  }
  for (const [re, text] of FACTS) {
    if (out.length >= 3) break;
    if (!re.test(q)) continue;
    if (/^복근/.test(text) !== (intent === 'progress') && intent === 'progress') continue;
    // 그립 줄은 대체 종목을 묻는 질문에는 붙이지 않는다(대체 짝이 먼저)
    if (/^그립/.test(text) && ASKS_SWAP.test(q) && !/그립|엄지|썸리스/.test(q)) continue;
    out.push(text);
  }
  return out;
}

/**
 * 의욕 질문의 "아주 작은 행동" 을 코드가 정한다 — 모델에 맡기면 남은 횟수를 요일에 나눠 주다 틀리거나
 * ("내일 가슴, 금 · 토에 2회" = 3회), 오늘 이미 운동한 회원에게 오늘 또 시킨다.
 */
export function stepFor(intent: Intent | string, r: SignalResult | null, data: string): string | null {
  if (intent !== 'motivation') return null;
  const first = planNames(data).match(/[:：]\s*([^,/]+?)\s*(,|\/|$)/)?.[1]?.trim();
  const what = first && first.length <= 16 ? `${first}만 3세트` : '플랜 첫 종목만 3세트';
  const doneToday = r?.todayDone ?? false;
  return doneToday
    ? `다음 운동 날 ${what}, 15분 (오늘은 이미 운동했으니 오늘 더 시키지 않는다)`
    : `오늘 ${what}, 15분`;
}

/**
 * 감량 중 회원이 먹어도 되냐고 묻는 습관(탄산 · 야식 · 매일 술) — 밀프 승인 경고 문형을 쓰게 한다.
 * 프롬프트의 warning 조건은 "하고 있다고 직접 말했을 때" 라 물어보기만 하면 경고가 안 나왔다. 판단은 코드가.
 * 돌려주는 것: 경고 문장의 ○○ 자리에 넣을 말. 제로 음료는 경고하지 않는다.
 */
export function warnFor(intent: Intent | string, phase: string | null | undefined, question: string): string | null {
  if (intent !== 'diet' || phase !== 'cut') return null;
  const q = question.replace(/\s+/g, ' ');
  if (/(콜라|사이다|탄산|환타|에너지\s?드링크)/.test(q) && !/제로|zero|0\s?칼로리|무가당|탄산수/i.test(q)) return '탄산음료';
  if (/야식/.test(q)) return '야식';
  if (/매일\s?(술|맥주|소주|한\s?잔)|술.{0,6}매일|맨날\s?(술|맥주|소주)/.test(q)) return '매일 마시는 술';
  return null;
}

const hasBatchim = (w: string) => {
  const c = w.charCodeAt(w.length - 1);
  return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0;
};

/** 대표 승인 경고 문형 */
export const warnLine = (what: string) => `회원님, 불편하시겠지만 ${what}${hasBatchim(what) ? '은' : '는'} 무조건 피하세요.`;
